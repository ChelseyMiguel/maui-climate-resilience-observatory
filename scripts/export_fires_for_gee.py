"""Emit the 2023 Upcountry fire perimeters as an Earth Engine geometry literal.

The Code Editor cannot read files on this machine, so the perimeters are pasted
into `scripts/gee/fire_perimeter_browning.js`. Full perimeters carry thousands of
vertices; they are simplified (Douglas-Peucker, ~10 m tolerance, one Sentinel-2
pixel) so the script stays pasteable without changing the area measurably.

    python scripts/export_fires_for_gee.py > /tmp/fires.js
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "data" / "research" / "maui_fire_perimeters.geojson"
UPCOUNTRY = {"Olinda", "Kula", "Pulehu"}
TOLERANCE_M = 10.0
M_PER_DEG = 111_320.0


def _perp_m(p, a, b, lat0):
    kx = M_PER_DEG * math.cos(math.radians(lat0))
    px, py = (p[0] - a[0]) * kx, (p[1] - a[1]) * M_PER_DEG
    bx, by = (b[0] - a[0]) * kx, (b[1] - a[1]) * M_PER_DEG
    length = math.hypot(bx, by)
    if length == 0:
        return math.hypot(px, py)
    return abs(bx * py - by * px) / length


def simplify(ring, lat0):
    """Iterative Douglas-Peucker; keeps the ring closed."""
    if len(ring) < 4:
        return ring
    keep = [False] * len(ring)
    keep[0] = keep[-1] = True
    stack = [(0, len(ring) - 1)]
    while stack:
        i, j = stack.pop()
        best, idx = 0.0, None
        for k in range(i + 1, j):
            d = _perp_m(ring[k], ring[i], ring[j], lat0)
            if d > best:
                best, idx = d, k
        if idx is not None and best > TOLERANCE_M:
            keep[idx] = True
            stack += [(i, idx), (idx, j)]
    out = [p for p, k in zip(ring, keep) if k]
    return out if len(out) >= 4 else ring


def polygons(geom):
    if geom["type"] == "Polygon":
        return [geom["coordinates"]]
    if geom["type"] == "MultiPolygon":
        return geom["coordinates"]
    return []


def main() -> None:
    fires = json.loads(SRC.read_text())["features"]
    before = after = 0
    print("// Generated by: python scripts/export_fires_for_gee.py")
    print(f"// Source: NIFC WFIGS perimeters, simplified at {TOLERANCE_M:g} m.")
    print("var fires = ee.FeatureCollection([")
    entries = []
    for f in fires:
        p = f["properties"]
        if p["year"] != 2023 or p["name"] not in UPCOUNTRY:
            continue
        polys = []
        for poly in polygons(f["geometry"]):
            lat0 = poly[0][0][1]
            rings = []
            for ring in poly:
                before += len(ring)
                s = simplify([(round(x, 6), round(y, 6)) for x, y in ring], lat0)
                after += len(s)
                rings.append([[x, y] for x, y in s])
            polys.append(rings)
        geom = json.dumps(polys, separators=(",", ":"))
        entries.append(
            f"  ee.Feature(ee.Geometry.MultiPolygon({geom}), "
            f"{{name: '{p['name']}', acres: {p['acres']}}})"
        )
    print(",\n".join(entries))
    print("]);")
    print(f"vertices {before} -> {after}", file=sys.stderr)


if __name__ == "__main__":
    main()
